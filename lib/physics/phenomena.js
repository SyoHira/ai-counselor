/** 単元に関係する現象 */
export function phenomenaFor(moduleId) {
  return PHENOMENA.filter((p) => p.modules.includes(moduleId));
}

export function phenomenonModules(p) {
  return p.modules.map((id) => MODULE_MAP.get(id)).filter(Boolean);
}
