  phd: `対象は博士課程・研究者レベル。既知の結果は要約でよい。
未解決点・仮定の弱点・数値的/実験的に検証可能な形へ落とす方法に重点を置く。
関連する原論文の著者名と年、主張の要点を挙げる（記憶が不確かな場合はその旨を明記する）。`,
