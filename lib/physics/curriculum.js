/** 学習順に並べた推奨パス（前提関係のトポロジカルソート、レベル順で安定化） */
export function learningPath(targetId) {
  const out = [];
  const seen = new Set();
  const visit = (id) => {
    if (seen.has(id)) return;
    seen.add(id);
    const m = MODULE_MAP.get(id);
    if (!m) return;
    for (const p of m.prereqs || []) visit(p);
    out.push(m);
  };
  visit(targetId);
  return out;
}

/**
 * 表示順を整える。領域ごとにまとめ、その中では前提の少ないものから並べる。
 * 配列の記載順に依存せず、学ぶ順に近い並びになる。
 */
// フィルタのチップは量子系を先頭に置くが、一覧の並びは学ぶ順に近い領域順にする
const DISPLAY_TRACK_ORDER = [
  'math', 'exp', 'mech', 'em', 'thermo', 'wave', 'rel',
  'qm', 'qinfo', 'cm', 'part', 'astro', 'comp',
];

export function sortForDisplay(list) {
  const trackIndex = new Map(DISPLAY_TRACK_ORDER.map((t, i) => [t, i]));
  const depthCache = new Map();
  const depth = (id, seen = new Set()) => {
    if (depthCache.has(id)) return depthCache.get(id);
    if (seen.has(id)) return 0;
    seen.add(id);
    const m = MODULE_MAP.get(id);
    const d = m ? (m.prereqs || []).reduce((a, p) => Math.max(a, depth(p, seen) + 1), 0) : 0;
    depthCache.set(id, d);
    return d;
  };
  return [...list].sort((a, b) => {
    const t = (trackIndex.get(a.track) ?? 99) - (trackIndex.get(b.track) ?? 99);
    if (t !== 0) return t;
    const d = depth(a.id) - depth(b.id);
    if (d !== 0) return d;
    return a.id.localeCompare(b.id);
  });
}

/** 検索（タイトル・要約・キーワード） */
export function searchModules(query) {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return MODULES.filter((m) =>
    [m.title, m.summary, ...(m.keywords || [])].join(' ').toLowerCase().includes(q)
  );
}

