export const MODULE_MAP = new Map(MODULES.map((m) => [m.id, m]));

export function getModule(id) {
  return MODULE_MAP.get(id) || null;
}

export function modulesByLevel(level) {
  return MODULES.filter((m) => m.level === level);
}

export function modulesByTrack(track) {
  return MODULES.filter((m) => m.track === track);
}

export function levelOf(id) {
  return LEVELS.find((l) => l.id === id) || LEVELS[0];
}

export function trackOf(id) {
  return TRACKS.find((t) => t.id === id) || TRACKS[0];
}

/** そのモジュールを前提にしている後続モジュール */
export function dependents(id) {
  return MODULES.filter((m) => (m.prereqs || []).includes(id));
}

/** 学習順に並べた推奨パス（前提関係のトポロジカルソート、レベル順で安定化） */
export function learningPath(targetId) {
  const out = [];
  const seen = new Set();
  const visit = (id) => {
    if (seen.has(id)) return;
    seen.add(id);
    const m = MODULE_MAP.get(id);
    if (!m) return;
    for (const p of m.prereqs || []) visit(p);
    out.push(m);
  };
  visit(targetId);
  return out;
}

/** 検索（タイトル・要約・キーワード） */
export function searchModules(query) {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return MODULES.filter((m) =>
    [m.title, m.summary, ...(m.keywords || [])].join(' ').toLowerCase().includes(q)
  );
}

