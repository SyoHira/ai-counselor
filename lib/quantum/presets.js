const g = (gate, target, controls = [], param) => ({ kind: 'gate', gate, target, controls, param });
const swap = (a, b, controls = []) => ({ kind: 'swap', target: a, target2: b, controls });
const measure = (target) => ({ kind: 'measure', target });

const PI = Math.PI;

// 3量子ビットGroverの拡散演算子（|000⟩まわりの反転）
function diffuser3() {
  return [
    g('H', 0), g('H', 1), g('H', 2),
    g('X', 0), g('X', 1), g('X', 2),
    g('H', 2), g('X', 2, [0, 1]), g('H', 2), // CCZ
    g('X', 0), g('X', 1), g('X', 2),
    g('H', 0), g('H', 1), g('H', 2),
  ];
}

// |101⟩（q0=1, q1=0, q2=1）に位相を付けるオラクル
function oracle101() {
  return [
    g('X', 1),
    g('H', 2), g('X', 2, [0, 1]), g('H', 2), // CCZ
    g('X', 1),
  ];
}

