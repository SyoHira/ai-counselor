ARTICLES = [A1, A2, A3]


def validate(articles: list[Article] | None = None, asset_keys: set[str] | None = None) -> list[str]:
    bad = []
    for a in articles or ARTICLES:
        text = a.title + "\n" + a.body
        for w in BANNED:
            if w in text:
                bad.append(f"{a.slug}：「{w}」")
        if URL.search(text) or EMAIL.search(text):
            bad.append(f"{a.slug}：URL・メールアドレス（リンクはプロフィールに置く）")
        for k in a.images:
            if f"［画像：{k}］" not in a.body:
                bad.append(f"{a.slug}：画像 {k} が本文に無い")
            if asset_keys is not None and k not in asset_keys:
                bad.append(f"{a.slug}：画像 {k} が無い")
    return bad


def unfilled(articles: list[Article] | None = None) -> list[str]:
    return [a.slug for a in (articles or ARTICLES) if MARK in a.body]


def render(a: Article) -> str:
    head = [f"<!-- {BRAND}の note 記事の下書き（{a.kind}）。`run brand` で作った文面。直すときは engine/n1engine/channels/articles.py を直す。",
            "     先頭の「# 」の行は記事のタイトル。［画像：名前］の場所に img/名前.png を入れる。-->", ""]
    if MARK in a.body:
        head += [f"<!-- ⚠ {MARK} を、実際の記録で埋めてから出す。作ったデータを自分の記録として出さない。-->", ""]
    return "\n".join(head + [f"# {a.title}", "", a.body.strip(), ""])


def export(out: str) -> list[str]:
    import pathlib

    root = pathlib.Path(out)
    root.mkdir(parents=True, exist_ok=True)
    written = []
    for a in ARTICLES:
        f = root / f"{a.slug}.md"
        f.write_text(render(a), encoding="utf-8")
        written.append(str(f))
    return written
