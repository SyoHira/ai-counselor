def post_weight_limit() -> int:
    return LIMITS["x_post_weighted"].value


def validate(posts: list[Post] | None = None, asset_keys: set[str] | None = None) -> list[str]:
    bad = []
    for ps in posts or POSTS:
        w = x_weight(ps.text)
        if w > post_weight_limit():
            bad.append(f"{ps.day}日目：{w}（上限 {post_weight_limit()}）")
        for b in BANNED:
            if b in ps.text:
                bad.append(f"{ps.day}日目：「{b}」")
        if URL.search(ps.text) or EMAIL.search(ps.text):
            bad.append(f"{ps.day}日目：URL・メールアドレス（リンクはプロフィールに置く）")
        if asset_keys is not None and ps.image and ps.image not in asset_keys:
            bad.append(f"{ps.day}日目：画像 {ps.image} が無い")
    return bad


def unfilled(posts: list[Post] | None = None) -> list[int]:
    return [ps.day for ps in (posts or POSTS) if MARK in ps.text]


